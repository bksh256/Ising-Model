# Make the 2D lattice 
def make_random_2D_lattice(lattice_side_length, generator):
    
    """Produces a randomly generated 2D lattice of +1 or -1 spins using a specific random seed and numpy's random number generator."""
    
    # PCG64DXSM is the most random number generator available in numpy.
    # True randomness is achieved by passing no seed - Seed is therefore sourced from the operating system 
    
    random_2D_lattice = generator.choice([1, -1], size=(lattice_side_length, lattice_side_length))

    return random_2D_lattice

# Function to calculate the energy for flipping a single spin  
def calculate_energy_MMC(lattice_side_length, random_2D_lattice, magnetic_field_B, temperature, exchange_constant_J, u_b, x_coord, y_coord):

    """Function for Metropolis Monte Carlo Algorithm: 
    
    Uses a nearest neighbour approach to calculate the energy change when a random spin is flipped.
    
    DOES NOT SUM OVER THE ENTIRE LATTICE TO CALCULATE ENERGY - NEAREST NEIGHBOURS ONLY.
    
    Requires the lattice, magnetic field, temperature, exchange constant and two randomly generated coordinates, generated by the MMC function 
    (Metropolis Monte Carlo).
    
    Periodic boundary conditions are enforced to keep the model physically accurate."""

    ## Ising model hamiltonian for 1 spin and its nearest neighbours using periodic boundary conditions ##

    # Nearest neighbours term of the hamiltonian
    nearest_neighbours_term = (-exchange_constant_J) * random_2D_lattice[x_coord, y_coord] * np.sum([random_2D_lattice[x_coord, (y_coord-1)%lattice_side_length], random_2D_lattice[x_coord, (y_coord+1)%lattice_side_length], random_2D_lattice[(x_coord-1)%lattice_side_length, y_coord], random_2D_lattice[(x_coord+1)%lattice_side_length, y_coord]])

    # Magnetic term of the hamiltonian
    magnetic_term = u_b * random_2D_lattice[x_coord, y_coord] * magnetic_field_B 

    # The energy is given by the subtraction of the magnetic term from the nearest neighbours term
    spin_flip_energy = nearest_neighbours_term - magnetic_term

    return spin_flip_energy

# Calculating lattice energy per spin
def calculate_lattice_energy_per_spin(lattice, lattice_side_length, exchange_constant_J, magnetic_field_B, u_b):

    """Calculates the total energy of the entire lattice using the same formula as the energy used to calculate a spin flip, just
    applied to the entire lattice than a specific set of spin coordinate"""

    # Uses np.roll to get periodic summation - Vectorised method of calculating the energy which is much faster than nested for loops
    periodic_boundary_sum = np.roll(lattice, 1, axis=0) + np.roll(lattice, -1, axis=0) + np.roll(lattice, 1, axis=1) + np.roll(lattice, -1, axis=1)

    # Nearest neighbour term in the hamiltonian
    nearest_neighbour_term = (-exchange_constant_J/2)*np.sum(lattice*periodic_boundary_sum)

    # Magnetic term in the hamiltonian
    magnetic_term = u_b*np.sum(magnetic_field_B*lattice)

    # Total lattice energy is given by the subtraction of the magnetic term from the hamiltonian term
    total_lattice_energy = nearest_neighbour_term - magnetic_term

    # Calculating the energy per spin
    energy_per_spin = total_lattice_energy / (lattice_side_length**2)

    return energy_per_spin

# Calculating magnetisation per spin
def calculate_magnetisation_per_spin(lattice, lattice_side_length):

    """Calculates the lattice magnetisation for a single 2D lattice."""

    # Using formula from the instructions to calculate the lattice magnetisation
    lattice_magnetisation_per_spin = (1/lattice_side_length**2)*np.sum(lattice)
    
    return lattice_magnetisation_per_spin

# Calculating internal magnetic field per spin
def calculate_internal_magnetic_field_per_spin(lattice, lattice_side_length, magnetic_field_B):

    """Calculates the internal magentic field strength of a single 2D lattice. Calls the lattice magnetisation function
    in order to get the lattice magnetisation."""

    # Extracting the magnetisation using the function to calculate it
    lattice_magnetisation_per_spin = calculate_magnetisation_per_spin(lattice, lattice_side_length)

    # Calculating the internal magnetic field using the magnetisation, bohr magneton and lattice magnetisation
    lattice_internal_magnetic_field_per_spin = (1/mu_0)*(magnetic_field_B-lattice_magnetisation_per_spin)

    return lattice_internal_magnetic_field_per_spin
    
# Function to perform MMC step
def MMC_step(lattice_side_length, random_2D_lattice, magnetic_field_B, temperature, k_b, u_b, exchange_constant_J, generator):

    """Performs a monte-carlo step - Calculates energies before and after the spin change and compares a randomly generated number to 
    the maxwell boltzmann distribution"""

    # PCG64DXSM is the most random number generator available in numpy.
    # True randomness is achieved by passing no seed - Seed is therefore sourced from the operating system.

    # Set of random coordinates
    x_coord = generator.integers(0, lattice_side_length)
    y_coord = generator.integers(0, lattice_side_length)

    # Calculating initial_energy
    old_energy = calculate_energy_MMC(lattice_side_length, random_2D_lattice, magnetic_field_B, temperature, exchange_constant_J, u_b, x_coord, y_coord)

    # Selecting a spin and flipping it 
    random_2D_lattice[x_coord, y_coord] *= -1

    # Calculating new energy
    new_energy = calculate_energy_MMC(lattice_side_length, random_2D_lattice, magnetic_field_B, temperature, exchange_constant_J, u_b, x_coord, y_coord)
    
    # Calculating energy change
    energy_change = new_energy - old_energy

    if energy_change > 0 and np.exp(-energy_change / (k_b * temperature)) < generator.random():

        # Undoing the flip if it isnt probable enough to happen
        random_2D_lattice[x_coord, y_coord] *= -1

    else:
        pass # Keep the spin flipped if the condition is not met 

    return random_2D_lattice

# Worker function for running an investigation simulation at a pre-defined temperature
def run_MMC_temp_investigation_worker(args):

    """Runs a single metropolis algorithm simulation at a pre-defined temperature, and takes its arguements as one object so this function 
        can be run in parallel across N cores across a temperature sweep, so multiple temperatures are investigated at the same time 
        by running this function multiple times using multiprocessing. """

    # Worker random generator
    generator = np.random.Generator(np.random.PCG64DXSM())

    # Extracting arguements from args object
    # Simulation parameters as a tuple so it will work with mutliple of these functions running in parallel
    (temperature, lattice_side_length, magnetic_field_B, exchange_constant_J, k_b, u_b, nsteps) = args
    
    # Initialising a random 2D lattice
    initial_lattice = make_random_2D_lattice(lattice_side_length, generator)
    
    # Creating the lattice used for the ising model simulation itself, leaving the initial lattice separate and unchanged.
    lattice = initial_lattice.copy()
    
    # Burn-in limit for calculations of variances - This is to account for equilibration
    burnin_step_proportion = 0.6
    burnin_equilibration_steps_threshold = int(burnin_step_proportion*nsteps)

    # Lists to store magnetisations, magnetic susceptibilities and heat capacity
    equilibrated_lattice_magnetisation_per_spin_list = []
    equilibrated_lattice_energy_per_spin_list = []
        
    ### MAIN SIMULATION LOOP ###
    for i in range(nsteps):

        # Reassigning the lattice with every step, making the ising model run. 
        lattice = MMC_step(lattice_side_length, lattice, magnetic_field_B, temperature, k_b, u_b, exchange_constant_J, generator)
            
        # Only begin the welford loop after equilibration - Past the burnin threshold.
        if i > burnin_equilibration_steps_threshold:

            # Calling functions on the lattice every timestep to calculate the quantities of interest
            lattice_magnetisation_per_spin = calculate_magnetisation_per_spin(lattice, lattice_side_length)
            lattice_energy_per_spin = calculate_lattice_energy_per_spin(lattice, lattice_side_length, exchange_constant_J, magnetic_field_B, u_b)

            # Appending function outputs to lists after the burn-in
            equilibrated_lattice_magnetisation_per_spin_list.append(lattice_magnetisation_per_spin)
            equilibrated_lattice_energy_per_spin_list.append(lattice_energy_per_spin)

    # Turning lists into arrays
    equilibrated_magnetisation_array = np.array(equilibrated_lattice_magnetisation_per_spin_list)
    equilibrated_energy_array = np.array(equilibrated_lattice_energy_per_spin_list)

    ## Computing thermodynamic quantities after the burn in ##

    # Magnetisation
    mean_magnetisation_per_spin = np.mean(np.abs(equilibrated_magnetisation_array))
    
    # Magnetisation burned-in variance
    magnetisation_burned_in_variance = np.var(np.abs(equilibrated_magnetisation_array))

    # Energy burned-in variance
    energy_burned_in_variance = np.var(equilibrated_energy_array)

    # Heat capacity
    heat_capacity_burned_in = ((lattice_side_length**2)/(k_b*(temperature**2)))*energy_burned_in_variance

    # Magnetic susceptibility burned-in
    magnetic_susceptibility_burned_in = ((lattice_side_length**2)/(k_b*(temperature)))*magnetisation_burned_in_variance

    return mean_magnetisation_per_spin, magnetic_susceptibility_burned_in, heat_capacity_burned_in